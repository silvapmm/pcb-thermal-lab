"""!
@file test_render_compare.py
@brief The independent reader and the vector truth (gerbonara + shapely) draw the same copper on our IC board, pixel by pixel: the pixels that differ are few and lie on an exact edge (README 4.45).
@details Needs gerbonara and shapely; uses the board generated by the repository (our_board.py), so no downloaded file is needed.
"""

import numpy as np
import pytest

pytest.importorskip("gerbonara")
pytest.importorskip("shapely")

import shapely

import gerber_geometry as gg
import native_gerber as ng
import our_board


def masks(tmp_path, pix):
    """!
    @brief The copper of our IC board by the independent reader and by the vector truth, on a grid shifted by an odd amount.
    @param tmp_path pytest temp dir.
    @param pix Pixel size (mm).
    @return Tuple (reader mask, truth mask, shapely geometry, window).
    """
    path = tmp_path / "board.gbr"
    path.write_text(our_board.gerber_text())
    geom, _ = gg.load_copper(path)
    window = (0.0137, our_board.SIZE - 0.0091, our_board.SIZE, our_board.SIZE)
    cv = ng.Canvas(window[0], window[1], window[2], window[3], pix)
    ng.Layer(path.read_text()).draw(cv)
    truth = gg.sample_mask(geom, window[0], window[1], window[2], window[3], pix) > 0.5
    return cv.mask, truth, geom, window


def test_vector_reference_includes_the_circular_tracks(tmp_path):
    """!@brief Regression: the vector reference ignored stroked arcs and found 41 mm2 on our board where the board has 164 mm2; it now agrees with the reader's area within 0.1 %. @param tmp_path pytest temp dir. @return None."""
    mine, truth, geom, window = masks(tmp_path, 0.02)
    assert abs(geom.area - mine.sum() * 0.02 ** 2) < 0.001 * geom.area
    assert geom.area > 150.0                                              # the arcs are there (without them the area is 41 mm2)


def test_reader_and_vector_truth_draw_the_same_copper(tmp_path):
    """!@brief At 0.05 mm every pixel that differs lies within the reader's own arc tolerance (5 micrometres) of an exact edge, the same number of pixels is copper only in one as only in the other, and the copper areas agree within 0.05 %. @param tmp_path pytest temp dir. @return None."""
    pix = 0.05
    mine, truth, geom, window = masks(tmp_path, pix)
    assert truth.sum() > 10000                                          # a real amount of copper
    diff = mine ^ truth
    rows, cols = np.where(diff)
    x, y = window[0] + (cols + 0.5) * pix, window[1] - (rows + 0.5) * pix
    assert (shapely.distance(shapely.points(x, y), geom.boundary)).max() < ng.ARC_TOLERANCE * 1.2     # millimetres
    assert abs(int((mine & ~truth).sum()) - int((~mine & truth).sum())) < 0.2 * diff.sum()               # no bias towards one side
    assert abs(mine.sum() - truth.sum()) < 0.0005 * truth.sum()
