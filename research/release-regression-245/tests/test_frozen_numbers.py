"""!
@file test_frozen_numbers.py
@brief Compares a run of the program in this tree with the numbers frozen at the release (`reference/v2.4.5.json`): bit for bit where nothing may move, within 1e-6 K elsewhere.
@details The frozen file is generated by `scripts/study_freeze_reference.py` from the final release candidate and the v2.4.4 baseline; until it exists the whole module is skipped
         with a message that says how to make it. The choice of what is run (a full run is long) is made by environment variables:

         * `PCBT_FROZEN_CELLS`: comma-separated cell sizes in mm (default "2", the fast set; "2,1,0.5" for everything);
         * `PCBT_FROZEN_BOARDS`: comma-separated board names (default all in the file);
         * `PCBT_FROZEN_MODELS`: comma-separated model keys (default all);
         * `PCBT_FROZEN_TRANSIENTS`: "1" to also compare the time to 63 % (default off);
         * `PCBT_FROZEN_BIT_TOL`: absolute tolerance in K for the records frozen as bit (default 0 = exact equality; set 1e-9 on another machine);
         * `PCBT_FROZEN_FILE`: another frozen file.
         Run: `QT_QPA_PLATFORM=offscreen .venv/bin/python -m pytest -q research/release-regression-245/tests/test_frozen_numbers.py`.
@note A failure is not automatically a defect: if the numbers moved for a reason that was decided (a model change), regenerate the file (INTEGRATION.md, "Updating the file") in
      the same commit and say why in the commit message; if nobody decided it, the change is a regression.
"""

import os
import sys
import tempfile
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(HERE.parent / "lib"))
sys.path.insert(0, str(REPO))

import regress_frozen as F                                                           # noqa: E402

FROZEN_FILE = Path(os.environ.get("PCBT_FROZEN_FILE", HERE.parent / "reference" / "v2.4.5.json"))
MISSING = not FROZEN_FILE.exists()
REASON = (f"the frozen numbers {FROZEN_FILE.name} do not exist yet: the tester makes them from the final release candidate with "
          "`.venv/bin/python research/release-regression-245/scripts/study_freeze_reference.py` (see research/release-regression-245/README.md)")


def _csv(name, default):
    """!
    @brief A comma-separated environment variable as a list.
    @param name Variable name.
    @param default Value when it is not set (a string, "" for no filter).
    @return List of non-empty strings.
    """
    return [v.strip() for v in os.environ.get(name, default).split(",") if v.strip()]


def _cases():
    """!
    @brief The (board, model, cell) triples to run: the frozen records that pass the filters of the environment variables.
    @return List of tuples, sorted by board then cell (one board is built once per module).
    """
    if MISSING:
        return []
    data = F.load(FROZEN_FILE)
    cells, boards, models = _csv("PCBT_FROZEN_CELLS", "2"), _csv("PCBT_FROZEN_BOARDS", ""), _csv("PCBT_FROZEN_MODELS", "")
    out = []
    for k in data["records"]:
        b, m, c = k.split("|")
        if float(c) in [float(x) for x in cells] and (not boards or b in boards) and (not models or m in models):
            out.append((b, m, float(c)))
    return sorted(out, key=lambda t: (t[0], t[2], t[1]))


@pytest.fixture(scope="module")
def frozen_data():
    """!
    @brief The frozen file.
    @return dict.
    """
    if MISSING:
        pytest.skip(REASON)
    return F.load(FROZEN_FILE)


@pytest.fixture(scope="module", autouse=True)
def private_config():
    """!
    @brief Run with an empty program configuration (no user defaults), as the frozen numbers were made.
    @return None (restores the environment after the module).
    """
    with pytest.MonkeyPatch().context() as mp:
        mp.setenv("PCBTHERMAL_CONFIG", tempfile.mkdtemp(prefix="pcbt_frozen_cfg_"))
        mp.setenv("QT_QPA_PLATFORM", "offscreen")
        yield


@pytest.fixture(scope="module")
def boards_cache():
    """!
    @brief Built boards by name (a board is built once and copied by the run).
    @return dict.
    """
    return {}


def test_the_frozen_file_is_present_or_the_module_says_why_it_is_skipped():
    if MISSING:
        pytest.skip(REASON)
    data = F.load(FROZEN_FILE)
    assert data["records"], "the frozen file has no records"
    assert data["version"], "the frozen file does not name its version"


@pytest.mark.parametrize("board,model,cell", _cases() or [pytest.param("-", "-", 0.0, marks=pytest.mark.skip(reason=REASON))])
def test_run_agrees_with_the_frozen_numbers(board, model, cell, frozen_data, boards_cache):
    import regress_boards as B
    import regress_harness as H
    if board not in boards_cache:
        boards_cache[board] = B.build(board)
    s = frozen_data["settings"]
    rec = H.run_one(boards_cache[board], board, model, cell, s["max_unknowns"], s["solid_cap"])
    diffs = F.compare(frozen_data, [rec], bit_tol_k=float(os.environ.get("PCBT_FROZEN_BIT_TOL", "0")))
    assert not diffs, "\n".join(diffs[:20])


@pytest.mark.skipif(os.environ.get("PCBT_FROZEN_TRANSIENTS", "0") != "1", reason="set PCBT_FROZEN_TRANSIENTS=1 to compare the times to 63 %")
@pytest.mark.parametrize("key", sorted(F.load(FROZEN_FILE)["transients"]) if not MISSING else [pytest.param("-", marks=pytest.mark.skip(reason=REASON))])
def test_time_to_63_percent_agrees_with_the_frozen_numbers(key, frozen_data, boards_cache):
    import regress_boards as B
    import regress_harness as H
    board, model = key.split("|")
    if board not in boards_cache:
        boards_cache[board] = B.build(board)
    t = H.t63(boards_cache[board], model, frozen_data["settings"]["transient_cell"])
    t["board"] = board
    diffs = F.compare(frozen_data, [], [t], bit_tol_k=float(os.environ.get("PCBT_FROZEN_BIT_TOL", "0")))
    assert not diffs, "\n".join(diffs[:20])
