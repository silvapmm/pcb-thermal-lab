"""!
@file test_our_board_models.py
@brief The IC board of our own as a bench for the mapping of copper to the thermal grid (phase 2).
@details The board has no licence problem (it is generated by this repository) and exercises circular tracks (arcs), rectangular pads, a large exposed pad with thermal vias, a ground ring and spoke, X2 net and aperture attributes and a plated drill file.
"""

import native_gerber as ng
import conduction as cd
import our_board as ob
import scenarios as sc



def draw(layer, pix, only=None):
    """!
    @brief The board's copper (or one net) as a mask on the whole 40 x 40 mm window.
    @param layer Parsed layer.
    @param pix Pixel size (mm).
    @param only Optional list of net names.
    @return Canvas.
    """
    cv = ng.Canvas(0.0, ob.SIZE, ob.SIZE, ob.SIZE, pix)
    layer.draw(cv, only)
    return cv


def test_mapping_to_the_thermal_grid_on_the_ic_board():
    """!@brief 1 W under the IC, border held at 0 K, h = 10, 1 mm cells, against the 0.1 mm mask solved pixel by pixel: the fill fraction is cool (about -6 %), the geometric mean hot (about +13 %), the flow-based faces within 8 % (about +4 %). @return None."""
    layer = ng.Layer(ob.gerber_text())
    S = cd.sheet_of(draw(layer, 0.1).mask[::-1])
    power, fixed, heater = sc.box_scenario(S.shape, 0.1, 6.0)
    _, em, _ = sc.compare(S, 0.1, 10, power, fixed, 10.0, heater, a=cd.S_CU, b=cd.S_LAM)
    assert em["fill fraction (today)"] < -3.0
    assert em["geometric mean"] > 8.0
    assert abs(em["flow-based faces"]) < 8.0
    assert abs(em["flow-based faces"]) < abs(em["geometric mean"])

