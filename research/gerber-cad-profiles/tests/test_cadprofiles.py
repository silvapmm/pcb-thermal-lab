def one(name, head):
    """!
    @brief Detect a single-file set.
    @param name  File name.
    @param head  Head text.
    @return Detection.
    """
    return cp.detect_set({name: head.encode("latin-1")})


@pytest.mark.parametrize("profile,version,name,head", CASES)
def test_real_banners(profile, version, name, head):
    """!
    @brief A file with the banner of a tool is recognised as that tool, with a high confidence, from that single file.
    @param profile  Expected profile.
    @param version  Fragment of the expected version text.
    @param name     File name.
    @param head     Head text.
    @return None
    """
    d = one(name, head)
    assert d.profile == profile
    assert d.confidence == "high"
    assert version in d.version


def test_table_is_consistent():
    """!
    @brief Every marker regex compiles, ids are unique inside a profile, weights are 1..10 and every status says where the evidence comes from.
    @return None
    """
    import re
    t = cp.load_table()
    for key, prof in t["profiles"].items():
        ids = [m["id"] for m in prof["markers"]]
        assert len(ids) == len(set(ids)), key
        assert prof["kind"] in ("ecad", "cam")
        for m in prof["markers"]:
            re.compile(m["re"])
            assert 1 <= m["w"] <= 10
            assert m["scope"] in ("gerber", "drill", "support", "name", "odb")
            assert m["status"][:1] in ("R", "D", "M")


def test_variant_wins_over_parent():
    """!
    @brief CircuitMaker writes the Altium Designer macro file as well: the variant is proposed, with no conflict.
    @return None
    """
    files = {"p.GBL": b"G04 #@! TF.GenerationSoftware,Altium Limited,CircuitMaker,2.2.1 (2.2.1.6)*\n",
             "p-macro.APR_LIB": b"G04:AMPARAMS|DCode=30|XSize=1mm*\n"}
    d = cp.detect_set(files)
    assert d.profile == "circuitmaker" and d.confidence == "high"


def test_mixed_set():
    """!
    @brief Files of two eCAD programs in one set: the one with more files is proposed and the confidence says "mixed".
    @return None
    """
    files = {"a-F_Cu.gbr": CASES[0][3].encode(), "a-B_Cu.gbr": CASES[0][3].encode(), "x.art": CASES[8][3].encode()}
    d = cp.detect_set(files)
    assert d.profile == "kicad" and d.confidence == "mixed"
    assert any(c[0] == "allegro" for c in d.candidates)


def test_cam_tool_never_overrides_ecad():
    """!
    @brief A CAM tool banner in one file does not outvote an eCAD banner in another.
    @return None
    """
    files = {"a.gbr": CASES[0][3].encode(), "b.gbr": CASES[-1][3].encode()}
    d = cp.detect_set(files)
    assert d.profile == "kicad"


def test_unknown_and_declared():
    """!
    @brief No marker: unknown.  An X2 generator not in the table: unknown, "declared" with the text.  A name only: low confidence.
    @return None
    """
    d = cp.detect_set({"x.gbr": b"%FSLAX24Y24*%\n%MOIN*%\nM02*\n"})
    assert d.profile == "unknown" and d.confidence == "unknown"
    d = cp.detect_set({"x.gbr": b"%TF.GenerationSoftware,Acme,BoardPlot,3.1*%\n%FSLAX24Y24*%\n"})
    assert d.profile == "unknown" and d.confidence == "declared" and d.declared == "Acme BoardPlot 3.1"
    d = cp.detect_set({"x.GTL": b"%FSLAX24Y24*%\n"})
    assert d.confidence in ("low", "unknown")


def test_file_scope():
    """!
    @brief Gerber, Excellon (also with a comment header or a leading percent line), ODB++ info and other text are told apart.
    @return None
    """
    assert cp.file_scope("a.gbr", "G04 x*\n%FSLAX24Y24*%") == "gerber"
    assert cp.file_scope("a.drl", "M48\nINCH\n") == "drill"
    assert cp.file_scope("a.drl", "; comment\n;x\nM48\n") == "drill"
    assert cp.file_scope("a.txt", "%\nM48\nINCH\n") == "drill"
    assert cp.file_scope("odb/misc/info", "JOB_NAME=job") == "odb"
    assert cp.file_scope("a.txt", "hello") == "support"


