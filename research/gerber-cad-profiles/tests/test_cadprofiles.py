def test_labels():
    """!
    @brief The X2 truth and the hand rules.
    @return None
    """
    assert labels.x2_truth("%TF.FileFunction,Copper,L2,Inr,Signal*%") == ("copper", "inner")
    assert labels.x2_truth("; #@! TF.FileFunction,MixedPlating,1,2") == ("drill", None)
    assert labels.x2_truth("G04 nothing") is None
    assert labels.rule_truth("xpedition", "SolderPasteTop.gdo") == ("paste", "top")
    assert labels.rule_truth("allegro", "ASSEM_BOT.art") == ("other", None)
    assert labels.rule_truth("allegro", "MASK_BOT.art") == ("soldermask", None)


def test_outline_prune():
    """!
    @brief A rectangle with a dangling stub is refused by the program and closes after pruning.
    @return None
    """
    from pcbthermal import gerber as G
    import outline_prune as op
    gbr = "%FSLAX24Y24*%\n%MOMM*%\n%ADD10C,0.1*%\nD10*\nX0Y0D02*\nX100000Y0D01*\nY50000D01*\nX0D01*\nY0D01*\nX50000Y0D02*\nY-20000D01*\nM02*\n"
    lay = G.parse_layer(gbr, "o.gbr")
    with pytest.raises(Exception):
        G.outline_from_layer(lay, 0.01)
    loops, dup, dang = op.outline_pruned(lay, 0.01)
    assert len(loops) == 1 and dang >= 1
    xs = loops[0][:, 0]
    assert abs(xs.max() - xs.min() - 10.0) < 1e-6


