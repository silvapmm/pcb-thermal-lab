CELL_MM = 2.0


def parse_jlc(key):
    """!
    @brief Copper and gap lists of one JLCPCB entry.
    @param key (layers, board thickness in mm, inner copper in oz) key of JLC.
    @return tuple (copper list in um, list of (kind, thickness in um)) with kind "P" (prepreg) or "C" (core).
    """
    n = key[0]
    inner, gaps = JLC[key]
    cu = [35.0] + [float(inner)] * (n - 2) + [35.0]
    g = [(w[0], float(w[1:])) for w in gaps.split()]
    return cu, g


def tmax(cu, gaps):
    """!
    @brief Maximum FVM temperature of the example board with the given stack-up and a full plane on every inner layer.
    @param cu Copper thickness per layer in um.
    @param gaps Dielectric thickness per gap in um.
    @return float Temperature in degC.
    """
    gaps = [x[1] if isinstance(x, tuple) else x for x in gaps]     # JLCPCB gaps carry their kind
    p = board(len(cu), cu, gaps, planes=True)
    return simulate(p, SolverOptions(models=("fvm",), cell_mm=CELL_MM)).results["fvm"].t_max


def program_tmax(p):
    """!
    @brief Maximum FVM temperature of a ready Problem.
    @param p Problem.
    @return float Temperature in degC.
    """
    return simulate(p, SolverOptions(models=("fvm",), cell_mm=CELL_MM)).results["fvm"].t_max


def isola_variant(n, inner_um=35.0, residual=0.5):
    """!
    @brief The template with 35 um inner copper where only the prepreg is thinned, by the resin that fills the etched copper (Isola rule).
    @details Cu-to-Cu dielectric space = overall prepreg thickness - etched fraction x copper thickness of each adjacent layer. Going from 15.2 to 35 um
             the extra copper buried by a prepreg is (inner_um - 15.2) um x (1 - residual) for each adjacent inner layer; cores are bought thicknesses and keep theirs.
    @param n Number of copper layers.
    @param inner_um Inner copper thickness in um.
    @param residual Residual (not etched) fraction of the inner copper, 0..1.
    @return Problem.
    """
    p = template_board(n)
    b = p.board
    kinds = [d["kind"] for d in stackup_template(n)["dielectrics"]]
    for l in range(1, n - 1):
        b.copper_thickness[l] = inner_um * 1e-6
    for g, kind in enumerate(kinds):
        if kind != "prepreg":
            continue
        adj = sum(1 for l in (g, g + 1) if 1 <= l <= n - 2)          # inner layers that touch this prepreg
        b.dielectrics[g].thickness -= adj * (1 - residual) * (inner_um - 15.2) * 1e-6
    b.thickness = b.total_thickness()
    return p


def split(cu, gaps):
    """!
    @brief Totals of a build.
    @param cu Copper per layer in um.
    @param gaps List of (kind, thickness in um) or plain thicknesses.
    @return tuple (copper total, core total, prepreg total, board total) in um; plain thicknesses count as prepreg.
    """
    g = [x if isinstance(x, tuple) else ("P", x) for x in gaps]
    c = sum(t for k, t in g if k == "C")
    pp = sum(t for k, t in g if k == "P")
    return sum(cu), c, pp, sum(cu) + c + pp


