"""!
@file study_real_1oz_stackups.py
@brief What do fabricators really use for the dielectric thicknesses when the inner copper is 1 oz, and which rule should the program's 1 oz variant follow?

@details Question (maintainer): the 1 oz (about 35 um) variant of the stack-up templates keeps the nominal board thickness by scaling every dielectric by one
         factor (0.97 for 4 layers down to 0.91 for 12, see `study_inner_copper_1oz.py`). Do real 1 oz builds thin the prepreg and the cores in proportion, thin only
         the prepreg (the resin fills the etched copper), or keep the dielectrics and let the board be thicker?
         This script holds the published 1 oz inner-copper stack-ups that could be read, each with its source and the way it was read, and prints
         (1) the pressed-prepreg rule check (Isola, PCBWay, AdvancedPCB), (2) the JLCPCB 0.5 oz and 1 oz builds side by side (same fabricator, same tool, same
         board thickness: this isolates what a fabricator changes when the inner copper goes from 0.5 oz to 1 oz), (3) the maximum temperature of the example board
         (FVM, 2 mm, full plane on every inner layer, as in `stackup_vendor_check.py`) for every real build, for the program's shipped template, for the unscaled
         and the scaled 1 oz variants and for a variant that thins only the prepreg as the Isola rule says.
         Results are in `research/stackup/README.md` section 4.6.

Usage: python research/stackup/scripts/study_real_1oz_stackups.py   (from the repository root; about 4 minutes)
"""

