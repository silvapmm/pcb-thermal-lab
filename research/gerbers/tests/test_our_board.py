"""!
@file test_our_board.py
@brief The IC board of our own (our_board.py) as a test bench: its nets, clearances, holes and vias, the resistance of a long arc track, and the mapping of its copper to the thermal grid.
@details The board has no licence problem (it is generated by this repository) and exercises circular tracks (arcs), rectangular pads, a large exposed pad with thermal vias, a ground ring and spoke, X2 net and aperture attributes and a plated drill file.
"""

import numpy as np
import pytest
from scipy import ndimage

import conduction as cd
import joule
import native_gerber as ng
import nets
import our_board as ob
import scenarios as sc
from study_net_joule import disc, net_pads

EIGHT = np.ones((3, 3))


def draw(layer, pix, only=None):
    """!
    @brief The board's copper (or one net) as a mask on the whole 40 x 40 mm window.
    @param layer Parsed layer.
    @param pix Pixel size (mm).
    @param only Optional list of net names.
    @return Canvas.
    """
    cv = ng.Canvas(0.0, ob.SIZE, ob.SIZE, ob.SIZE, pix)
    layer.draw(cv, only)
    return cv


def test_nets_are_found_each_in_one_piece_and_never_touch():
    """!@brief Nine nets (S1 to S8, GND), each one 8-connected piece, no pixel of a net within a pixel of another (no short, clearance at least 0.05 mm). @return None."""
    layer = ng.Layer(ob.gerber_text())
    assert layer.net_names() == [ob.net_name(k) for k in range(ob.N_SIG)] + ["GND"]
    full = draw(layer, 0.05)
    assert ndimage.label(full.mask, structure=EIGHT)[1] == 9
    masks = {n: draw(layer, 0.05, [n]).mask for n in layer.net_names()}
    for n, m in masks.items():
        assert ndimage.label(m, structure=EIGHT)[1] == 1, n
    names = list(masks)
    for i, a in enumerate(names):
        grown = ndimage.binary_dilation(masks[a], structure=EIGHT)
        for b in names[i + 1:]:
            assert not (grown & masks[b]).any(), (a, b)
    assert sum(int(m.sum()) for m in masks.values()) == int(full.mask.sum())      # the nets do not overlap


def test_drill_file_matches_pads_and_nets():
    """!@brief The 16 plated holes: 8 vias (four thermal vias in the exposed pad, four on the ring, net GND) and 8 test-point holes (nets S1 to S8), each with the same net found by position. @return None."""
    import tempfile
    from pathlib import Path
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "pth.drl"
        path.write_text(ob.drill_text())
        assert ng.drill_function(path) == (True, 1, 1)
        h = ng.read_drill(path)
    assert len(h) == 16 and all(p for *_, p in h)
    rep = nets.hole_report(h, [("F", ng.Layer(ob.gerber_text()))])
    s = nets.summarize(rep)
    assert s["kinds"] == {"via": 8, "component": 8} and s["same_net"] == 16 and s["conflicting_nets"] == 0 and s["no_net"] == 0
    assert sorted(r["net"] for r in rep if r["kind"] == "component") == sorted(ob.net_name(k) for k in range(ob.N_SIG))
    assert {r["net"] for r in rep if r["kind"] == "via"} == {"GND"}


def test_arc_track_resistance_against_the_hand_estimate():
    """!@brief The longest signal net (S1: a radial stub and a 150 degree arc of 0.2 mm track, 229 squares) has the resistance of its squares within +15 % (the five-point stencil is a little too resistive on a curved track, README 4.23), and its heat is I^2 R. @return None."""
    layer = ng.Layer(ob.gerber_text())
    pix = 0.025
    cv = draw(layer, pix, ["S1"])
    pa = np.array(net_pads(layer, "S1"))
    assert len(pa) == 2
    src, snk = (disc(cv.mask.shape, cv, p[0], p[1], 0.25) & cv.mask for p in pa)
    r, v, q = joule.solve_net(cv.mask, joule.resistivity(20.0) / 35e-6, src, snk, 1.0)
    hand = ob.squares(0) * joule.resistivity(20.0) / 35e-6
    assert hand * 0.95 < r < hand * 1.15
    assert q.sum() == pytest.approx(r, rel=1e-9)


def test_mapping_to_the_thermal_grid_on_the_ic_board():
    """!@brief 1 W under the IC, border held at 0 K, h = 10, 1 mm cells, against the 0.1 mm mask solved pixel by pixel: the fill fraction is cool (about -6 %), the geometric mean hot (about +13 %), the flow-based faces within 8 % (about +4 %). @return None."""
    layer = ng.Layer(ob.gerber_text())
    S = cd.sheet_of(draw(layer, 0.1).mask[::-1])
    power, fixed, heater = sc.box_scenario(S.shape, 0.1, 6.0)
    _, em, _ = sc.compare(S, 0.1, 10, power, fixed, 10.0, heater, a=cd.S_CU, b=cd.S_LAM)
    assert em["fill fraction (today)"] < -3.0
    assert em["geometric mean"] > 8.0
    assert abs(em["flow-based faces"]) < 8.0
    assert abs(em["flow-based faces"]) < abs(em["geometric mean"])
