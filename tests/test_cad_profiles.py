SKIP_EXT = {".zip", ".tgz", ".pdf", ".png", ".bmp", ".jpg", ".dxf", ".3ds", ".gz"}


def _collect(root):
    """!
    @brief Read the first 8 kB of every usable file under a sample folder (nested sets and copies left out).
    @param root Folder.
    @return dict Name relative to the folder -> first bytes.
    """
    out = {}
    skip = NESTED.get(os.path.basename(root.rstrip("/")), set())
    for dp, dn, fs in os.walk(root):
        dn[:] = [x for x in dn if x not in skip]
        for f in fs:
            p = os.path.join(dp, f)
            if os.path.splitext(f)[1].lower() in SKIP_EXT or os.path.getsize(p) == 0 or f in ("_SOURCE.txt", "LICENSE", "README", "SOURCE", "listing.json"):
                continue
            with open(p, "rb") as fh:
                out[os.path.relpath(p, root)] = fh.read(pr.HEAD_BYTES)
    return out


@pytest.mark.skipif(not SAMPLES or not os.path.isdir(SAMPLES), reason="PCBT_GERBER_SAMPLES not set")
def test_research_samples_development_and_heldout():
    """!
    @brief On the 54 development sets every tool with a profile is recognised, the Zuken emulation and the unlabelled set are not claimed (no profile), and the 28 held-out
           sets (other repositories, other versions) are all recognised.
    @return None
    """
    wrong = []
    claimed = 0
    for root, truth in DEV_SETS:
        d = pr.detect_profile(_collect(os.path.join(SAMPLES, root)))
        if truth in ("zuken", "unknown"):
            claimed += d.profile not in ("unknown", "declared")
            if d.profile not in ("unknown", "declared"):
                wrong.append((root, d.profile))
        elif d.profile != truth or pr.choose(d).key != truth:
            # recognised AND applied (a "low" result names the tool but does not apply it)
            wrong.append((root, d.profile, d.confidence))
    assert not wrong, wrong
    assert len(DEV_SETS) == 54 and claimed == 0
    base = os.path.join(SAMPLES, "heldout")
    if os.path.isdir(base):
        miss = []
        sets = sorted(os.listdir(base))
        for s in sets:
            truth = s.split("__")[0]
            d = pr.detect_profile(_collect(os.path.join(base, s)))
            if d.profile != truth or d.confidence != "high":
                miss.append(s)
        assert not miss and len(sets) == 28, (miss, len(sets))
