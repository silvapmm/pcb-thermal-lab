def test_banner_private_text_never_comes_out():
    """!
    @brief The path, user and computer of an Xpedition banner appear in no output: not in the evidence, the public dict, the summary, the choice or any repr.
    @return None
    """
    d = pr.detect_profile({"EtchLayerTop.gdo": SECRET_HEAD.encode()})
    assert d.profile == "xpedition"
    pub = pr.public_evidence(d)
    blob = repr(d) + repr(pub) + pr.summary(d) + repr(pr.choose(d)) + repr(pr.choose(d).record())
    for secret in ("secret", "someone", "MYHOST", "PCB.pcb", "C:"):
        assert secret not in blob
    assert ("g_job", 1) in pub["markers"]
    assert not hasattr(d.evidence[0], "text")
    # a project name or user inside a version field is cut to printable ASCII without markup
    d = pr.detect_profile({"x.gbr": b"%TF.GenerationSoftware,KiCad,Pcbnew,9.0 <b>x</b> & C:\\Users\\me\\" + b"y" * 200 + b"*%\n%FSLAX24Y24*%\n"})
    pub = pr.public_evidence(d)
    assert len(pub["version"]) <= pr.PUBLIC_TEXT_MAX
    assert not set("<>&\\") & set(pub["version"])
    d = pr.detect_profile({"x.gbr": b"%TF.GenerationSoftware,Acme <b>Evil</b>,Plot" + b"x" * 200 + b",1*%\n%FSLAX24Y24*%\n"})
    pub = pr.public_evidence(d)
    assert len(pub["declared"]) <= pr.PUBLIC_TEXT_MAX and not set("<>&") & set(pub["declared"]) and not set("<>&") & set(pub["line"])
    assert pr.public_text("a\x00b\x1b[31m\u00e9z") == "ab[31mz"


def test_hostile_inputs():
    """!
    @brief Huge heads, binary heads, str heads, a thousand members and names with markup or control characters end in a result, quickly.
    @return None
    """
    t0 = time.perf_counter()
    assert pr.detect_profile({"x.gbr": (b"G04 " * 300000) + b"%FSLAX24Y24*%"}).profile == "unknown"
    assert pr.detect_profile({"x.gbr": b"%" + b"A" * 1000000}).profile == "unknown"
    assert pr.detect_profile({"x.gbr": b"\r" * 1000000}).profile == "unknown"
    assert pr.detect_profile({"x.bin": bytes(range(256)) * 4000}).profile == "unknown"
    assert pr.detect_profile({"x.gbr": "%FSLAX24Y24*%\n%TF.GenerationSoftware,KiCad,Pcbnew,9.0*%\n" * 100}).profile == "kicad"        # a str head
    assert pr.detect_profile({}).profile == "unknown"
    names = {"<img src=x onerror=alert(1)>%s.GTL" % ("a" * 5000): GERBER.encode(), "a\x00b\nc.gbr": b"G04 PROTEUS GERBER X2 FILE*\n"}
    d = pr.detect_profile(names)
    assert d.profile == "proteus"
    many = {"f%05d.gbr" % i: CASES[0][3].encode() for i in range(pr.MAX_FILES + 500)}
    d = pr.detect_profile(many)
    assert d.profile == "kicad" and len({h.file for h in d.evidence}) <= pr.MAX_FILES
    # the table is read once and the work is bounded: the whole block must stay far below a second
    assert time.perf_counter() - t0 < 5.0


def _adversarial_heads(table):
    """!
    @brief Heads built to make a backtracking pattern slow: blanks, newlines, each marker's own literal prefix repeated or followed by blanks and by one long field.
    @param table The marker table.
    @return list Head texts of 8 kB.
    """
    heads = [" " * 8192, "\n" * 8192, "\t" * 8192, "G04 " * 2048, "TF.GenerationSoftware," * 400, "%IN1=" * 1600, "G04 Job   :" * 700, ";" * 8192, "=" * 8192]
    for prof in table["profiles"].values():
        for m in prof["markers"]:
            lit = re.match(r"(?:\(\?[a-z]+\))?((?:[^\\\[\](){}.*+?|^$]|\\.)+)", m["re"])
            prefix = re.sub(r"\\(.)", r"\1", lit.group(1)) if lit else ""
            if not prefix:
                continue
            for tail in ("", " ", "a", "\n", ",", "1", "*"):
                heads.append((prefix + tail) * (8192 // (len(prefix) + len(tail)) + 1))
            heads.append(prefix + " " * 8192)
            heads.append(prefix + "a" * 8192)
            heads.append(prefix + "\n" * 8192)
    return [h[:8192] for h in heads]


def test_every_pattern_has_a_linear_worst_case():
    """!
    @brief Adversarial 8 kB heads (also behind a Gerber or an Excellon opening line) cost milliseconds per set, and doubling the head does not quadruple the cost.
    @details The review of the research prototype found two quadratic patterns (adjacent quantifiers over the same characters). Every pattern of the table is bounded now.
    @return None
    """
    table = pr.load_table()
    heads = _adversarial_heads(table)
    worst = 0.0
    for h in heads:
        for opening in ("", "%FSLAX24Y24*%\n", "M48\n"):
            raw = (opening + h).encode("latin-1", "replace")
            t0 = time.perf_counter()
            pr.detect_profile({"x.gbr": raw, "y.art": raw, "z.GTL": raw})
            worst = max(worst, time.perf_counter() - t0)
    assert worst < 0.25, "slowest adversarial set took %.3f s" % worst
    # the cap on the head makes 8 kB the worst case; check the scaling of the pattern work on a head that fills it
