def one(name, head):
    """!
    @brief Detect a single-file set.
    @param name File name.
    @param head Head text.
    @return ProfileResult.
    """
    return pr.detect_profile({name: head.encode("latin-1")})


@pytest.mark.parametrize("profile,version,name,head", CASES)
def test_banners(profile, version, name, head):
    """!
    @brief A file with the banner of a tool is recognised as that tool, with a high confidence, from that single file.
    @param profile Expected profile.
    @param version Fragment of the expected version text.
    @param name File name.
    @param head Head text.
    @return None
    """
    d = one(name, head)
    assert d.profile == profile
    assert d.confidence == "high"
    assert version in d.version


def test_table_is_consistent_and_has_no_untested_tool():
    """!
    @brief The table is valid, every profile has only the allowed keys, there is no profile for a tool without a real sample and nothing presets the bottom X sign.
    @return None
    """
    t = pr.load_table()
    assert pr.table_version(t) >= 1
    allowed = {"name", "kind", "parent", "markers", "name_rules", "name_rules_status"}
    for key, prof in t["profiles"].items():
        assert set(prof) <= allowed, key
    for banned in ("zuken", "cadstar", "padspro", "xpeditionvx", "allegrox", "orcadx", "easyedapro", "horizon"):
        assert banned not in t["profiles"]
    assert "unknown" in t["profiles"] and "declared" in t["profiles"]
    assert "bottom_x" not in json.dumps(t["profiles"])      # the sign of the bottom-side X is detected from the paste openings, never preset
    # the name rules of PADS and EAGLE are from memory and say so
    assert pr.rules_from_memory("pads") and pr.rules_from_memory("eagle")
    assert not pr.rules_from_memory("xpedition") and not pr.rules_from_memory("allegro")
    # every marker with a weight of 9 or more names a status (R, D or M) and the shipped table has no emulation-only (D) marker
    for prof in t["profiles"].values():
        for m in prof["markers"]:
            assert not (m["w"] >= pr.DECISIVE and m["status"].startswith("D"))


def test_table_validation_rejects_bad_tables(tmp_path):
    """!
    @brief A table with a bad pattern, weight or rule is refused with a ValueError.
    @param tmp_path Temporary folder.
    @return None
    """
    good = json.loads(json.dumps(pr.load_table()))
    for mutate in (lambda t: t["profiles"]["kicad"]["markers"][0].update(re="("),
                   lambda t: t["profiles"]["kicad"]["markers"][0].update(w=11),
                   lambda t: t["profiles"]["kicad"]["markers"][0].update(status="X"),
                   lambda t: t["profiles"]["xpedition"]["name_rules"].append(["a", "nonsense", None]),
                   lambda t: t["profiles"].pop("unknown")):
        bad = json.loads(json.dumps(good))
        mutate(bad)
        with pytest.raises(ValueError):
            pr._validate(bad)
    path = tmp_path / "t.json"
    path.write_text(json.dumps(good))
    assert pr.load_table(str(path))["version"] == good["version"]


