def test_choose_user_override_replaces_only_the_profile_tier():
    """!
    @brief The user's profile replaces the detection ("user" source), an unknown key is refused, and X2 still wins over the rules of the chosen profile.
    @return None
    """
    d = one("x.art", CASES[10][3])
    assert pr.choose(d) == pr.ProfileChoice("allegro", "detected", pr.table_version())
    c = pr.choose(d, "xpedition")
    assert c.key == "xpedition" and c.source == "user" and c.record() == {"key": "xpedition", "source": "user", "table": pr.table_version()}
    assert pr.choose(d, "unknown").key == "unknown"
    with pytest.raises(ValueError):
        pr.choose(d, "not-a-tool")
    # X2 beats the profile: a file that states its function keeps it, whatever profile the user chose
    x2 = "%TF.FileFunction,Copper,L1,Top*%\n%FSLAX24Y24*%\n"
    assert detect_function("EtchLayerBottom.gdo", x2, "xpedition") == detect_function("EtchLayerBottom.gdo", x2)
    assert detect_function("EtchLayerBottom.gdo", x2, "xpedition").side == "top"


def test_name_rules_feed_the_function_detector_below_x2_and_header():
    """!
    @brief The profile's name rules decide files that the generic rules cannot, and change nothing for files that state their function.
    @return None
    """
    for name, head, profile, kind, side in (("EtchLayerTop.gdo", GERBER, "xpedition", "copper", "top"),
                                            ("EtchLayerBottom.gdo", GERBER, "xpedition", "copper", "bottom"),
                                            ("SolderPasteTop.gdo", GERBER, "xpedition", "paste", "top"),
                                            ("DRILL.gdo", GERBER, "xpedition", "other", None),
                                            ("BoardOutlline.gdo", GERBER, "xpedition", "outline", None),
                                            ("spt.art", GERBER, "allegro", "paste", "top"),
                                            ("MASK_SEC.art", GERBER, "allegro", "soldermask", "bottom"),
                                            ("ASSY1.art", GERBER, "allegro", "other", None),
                                            ("L2_GND.art", GERBER, "allegro", "copper", "inner"),
                                            ("Top.pho", GERBER, "pads", "copper", "top"),
                                            ("board.pastetop", GERBER, "target3001", "paste", "top"),
                                            ("k_Top.gbr", GERBER, "diptrace", "copper", "top"),
                                            ("board.group3.gbr", GERBER, "geda", "copper", "inner")):
        f = detect_function(name, head, profile)
        assert (f.kind, f.side) == (kind, side), (name, f)
        assert f.confidence == "low"            # a profile improves a name guess, it does not make it certain
    # the same file under the generic rules is not a top copper layer
    assert detect_function("EtchLayerTop.gdo", GERBER).kind != "copper" or detect_function("EtchLayerTop.gdo", GERBER).side != "top"
    # an Excellon header and an X2 function win over every profile
    drill = "M48\n;TYPE=PLATED\nMETRIC\n"
    for key in pr.profile_keys():
        assert detect_function("ThruHolePlated.ncd", drill, key) == detect_function("ThruHolePlated.ncd", drill)
        assert detect_function("a.gbr", "%TF.FileFunction,Paste,Bot*%\n%FSLAX24Y24*%", key) == detect_function("a.gbr", "%TF.FileFunction,Paste,Bot*%\n%FSLAX24Y24*%")


